// Bake the selected Kenney CC0 OBJ models to one compact mesh per prop.
// No runtime texture/OBJ loader; source palette samples become vertex colours.
const fs=require('node:fs'),path=require('node:path'),zlib=require('node:zlib');
const specs={
 container:{pack:'city',file:'shipping-container-a',size:6.2,rotate:true},
 crate:{pack:'blaster',file:'crate-wide',size:1.6,rotate:true},
 factory:{pack:'city',file:'building-g',size:12},
 waterTower:{pack:'city',file:'water-tower',size:12},
 tank:{pack:'city',file:'detail-tank',size:3.4},
 compressor:{pack:'factory',file:'machine-fortified',size:2},
 valve:{pack:'factory',file:'pipe-large-valve',size:1.5}
};
function png(filename){
 const data=fs.readFileSync(filename),width=data.readUInt32BE(16),height=data.readUInt32BE(20),parts=[];
 if(data[24]!==8||data[25]!==6||data[28]!==0)throw Error('Expected non-interlaced RGBA8 palette');
 for(let p=8;p<data.length;){const n=data.readUInt32BE(p),tag=data.toString('ascii',p+4,p+8);if(tag==='IDAT')parts.push(data.subarray(p+8,p+8+n));p+=n+12;}
 const raw=zlib.inflateSync(Buffer.concat(parts)),stride=width*4,rgba=Buffer.alloc(width*height*4);
 const paeth=(a,b,c)=>{const p=a+b-c,aa=Math.abs(p-a),bb=Math.abs(p-b),cc=Math.abs(p-c);return aa<=bb&&aa<=cc?a:bb<=cc?b:c;};
 for(let y=0;y<height;y++){const filter=raw[y*(stride+1)];for(let x=0;x<stride;x++){
  const i=y*stride+x,a=x>=4?rgba[i-4]:0,b=y?rgba[i-stride]:0,c=y&&x>=4?rgba[i-stride-4]:0;
  const predictor=filter===0?0:filter===1?a:filter===2?b:filter===3?Math.floor((a+b)/2):filter===4?paeth(a,b,c):NaN;
  if(!Number.isFinite(predictor))throw Error('Unknown PNG filter');rgba[i]=(raw[y*(stride+1)+x+1]+predictor)&255;
 }}
 return ([u,v])=>{const x=Math.max(0,Math.min(width-1,Math.floor(u*width))),y=Math.max(0,Math.min(height-1,Math.floor((1-v)*height)));return [...rgba.subarray((y*width+x)*4,(y*width+x)*4+3)];};
}
const palettes=Object.fromEntries(['city','factory','blaster'].map(pack=>[pack,png(path.join(__dirname,pack,'Textures/colormap.png'))]));
const packed={},bounds={},counts={};
for(const [kind,s] of Object.entries(specs)){
 const pos=[],norm=[],uv=[],faces=[];
 for(const line of fs.readFileSync(path.join(__dirname,s.pack,s.file+'.obj'),'utf8').split(/\r?\n/)){
  const [op,...v]=line.trim().split(/\s+/);if(op==='v')pos.push(v.slice(0,3).map(Number));if(op==='vn')norm.push(v.map(Number));if(op==='vt')uv.push(v.map(Number));if(op==='f')faces.push(v.map(x=>x.split('/').map(Number)));
 }
 const min=[0,1,2].map(c=>Math.min(...pos.map(p=>p[c]))),max=[0,1,2].map(c=>Math.max(...pos.map(p=>p[c]))),span=max.map((x,c)=>x-min[c]);
 const scale=s.size/Math.max(...span),mid=[(min[0]+max[0])/2,min[1],(min[2]+max[2])/2];
 const vertices=[],indices=[],known=new Map();
 for(const face of faces)for(let j=1;j<face.length-1;j++)for(const p of [face[0],face[j],face[j+1]]){
  const key=p.join('/');if(!known.has(key)){
   const xyz=pos[p[0]-1].map((x,c)=>(x-mid[c])*scale),sourceNormal=norm[p[2]-1],length=Math.hypot(...sourceNormal),n=sourceNormal.map(v=>v/length);let rgb=palettes[s.pack](uv[p[1]-1]);
   if(kind==='crate'&&rgb[2]>rgb[0]*1.15&&rgb[2]>rgb[1]*1.12){const shade=Math.max(.55,Math.min(1.2,rgb[2]/210));rgb=[79,111,132].map(v=>Math.round(v*shade));}
   const pp=s.rotate?[xyz[2],xyz[1],-xyz[0]]:xyz,nn=s.rotate?[n[2],n[1],-n[0]]:n,buffer=Buffer.alloc(12);
   pp.forEach((x,c)=>buffer.writeInt16LE(Math.round(x*1000),c*2));nn.forEach((x,c)=>buffer.writeInt8(Math.round(x*127),6+c));rgb.forEach((x,c)=>buffer.writeUInt8(x,9+c));
   known.set(key,vertices.length);vertices.push(buffer);
  }indices.push(known.get(key));
 }
 if(vertices.length>65535)throw Error('Prop index overflow');
 const indexBuffer=Buffer.alloc(indices.length*2);indices.forEach((x,i)=>indexBuffer.writeUInt16LE(x,i*2));
 packed[kind]=[Buffer.concat(vertices).toString('base64'),indexBuffer.toString('base64')];
 const size=span.map(v=>Math.round(v*scale*1000)/1000);bounds[kind]={w:s.rotate?size[2]:size[0],h:size[1],d:s.rotate?size[0]:size[2]};counts[kind]=indices.length/3;
}
const target=path.join(__dirname,'../../dist/assets/environment-props.js');
fs.writeFileSync(target,'// Kenney CC0 Factory Kit 3.0 + City Kit Industrial 2.0 + Blaster Kit 2.1. Generated by art-source/environment/bake-environment.cjs.\nexport const propData='+JSON.stringify(packed)+';\nexport const propBounds='+JSON.stringify(bounds)+';\n');
console.log(JSON.stringify({bounds,triangles:counts,total:Object.values(counts).reduce((a,b)=>a+b,0),bytes:fs.statSync(target).size},null,2));
