"""Bake the four editable Kenney OBJ models into the static browser build (Pillow required)."""
from base64 import b64encode
from collections import defaultdict
import json
from pathlib import Path
from struct import pack
from PIL import Image

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parents[1] / "dist" / "assets" / "blaster-geometry.js"
ATLAS = Image.open(ROOT / "Textures" / "colormap.png").convert("RGB")
SPECS = {
    # source, grip center in source coords, scale
    "rifle": ("d", (0, .048, .183), .84),
    "shotgun": ("j", (0, .055, .167), 1.09),
    "sniper": ("e", (-.045, .031, 1.06), .82),
    "pistol": ("c", (0, .034, .124), .7),
}

def encoded(values):
    return b64encode(values).decode("ascii")

def bake(name, grip, scale):
    positions, normals, uvs = [], [], []
    groups = defaultdict(list)
    group = "body"
    for line in (ROOT / ("blaster-" + name + ".obj")).read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        op, args = fields[0], fields[1:]
        if op == "g":
            group = args[0] if args[0] in ("scope", "magazine") else "body"
        elif op == "v":
            positions.append(tuple(map(float, args[:3])))
        elif op == "vn":
            normals.append(tuple(map(float, args[:3])))
        elif op == "vt":
            uvs.append(tuple(map(float, args[:2])))
        elif op == "f":
            for index in range(1, len(args) - 1):
                groups[group].extend((args[0], args[index], args[index + 1]))
    model = {}
    for group, points in groups.items():
        vertices = bytearray()
        indices = bytearray()
        known = {}
        for p in points:
            if p not in known:
                pi, ui, ni = (int(i) - 1 for i in p.split("/"))
                pos = [round((v - offset) * scale * 10000) for v, offset in zip(positions[pi], grip)]
                normal = [round(v * 127) for v in normals[ni]]
                u, v = uvs[ui]
                rgb = ATLAS.getpixel((round(u * (ATLAS.width - 1)), round((1-v) * (ATLAS.height - 1))))
                known[p] = len(vertices) // 12
                vertices.extend(pack("<3h3b3B", *pos, *normal, *rgb))
            indices.extend(pack("<H", known[p]))
        model[group] = [encoded(vertices), encoded(indices)]
    return model

if __name__ == "__main__":
    data = {kind:bake(name,grip,scale) for kind,(name,grip,scale) in SPECS.items()}
    OUTPUT.write_text("// Generated by art-source/blasters/bake.py. Model geometry by Kenney (CC0).\nexport const blasters = " + json.dumps(data, separators=(",", ":")) + ";\n")
